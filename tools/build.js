#!/usr/bin/env node
/*
 * Builds apps-script/dist/Code.gs = shared/osc-core.js + apps-script/src/*.js (in name order),
 * and copies shared files into the console. Run: node tools/build.js
 */
'use strict';
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');

const strip = (t) => t.replace(/\nif \(typeof module[^\n]*\n?$/, '\n');
const SHARED = ['rules.js', 'xlsx.js', 'pdf.js', 'billing.js', 'pack.js'];
const core = strip(read('shared/osc-core.js')) + SHARED.map((f) => '\n/* ----- shared/' + f + ' ----- */\n' + strip(read('shared/' + f))).join('');
const srcDir = path.join(root, 'apps-script/src');
const parts = fs.readdirSync(srcDir).filter((f) => f.endsWith('.js')).sort()
  .map((f) => `\n/* ----- ${f} ----- */\n` + fs.readFileSync(path.join(srcDir, f), 'utf8'));
const pkg = JSON.parse(read('package.json'));
const header = `/*\n * OutSource Connect — server code (Google Apps Script)\n * Version ${pkg.version}. GENERATED by tools/build.js — edit the files in apps-script/src and shared/, then rebuild.\n * Paste this whole file into the Apps Script editor as Code.gs.\n */\n`;
fs.mkdirSync(path.join(root, 'apps-script/dist'), { recursive: true });
fs.writeFileSync(path.join(root, 'apps-script/dist/Code.gs'), header + '\n/* ----- shared/osc-core.js ----- */\n' + core + parts.join('\n'));
fs.copyFileSync(path.join(root, 'apps-script/appsscript.json'), path.join(root, 'apps-script/dist/appsscript.json'));
fs.copyFileSync(path.join(root, 'shared/osc-core.js'), path.join(root, 'console/js/osc-core.js'));
fs.copyFileSync(path.join(root, 'shared/osc-core.js'), path.join(root, 'kiosk/js/osc-core.js'));
['rules.js', 'rule-cases.js', 'xlsx.js', 'pdf.js', 'billing.js', 'pack.js'].forEach((f) => fs.copyFileSync(path.join(root, 'shared', f), path.join(root, 'console/js', f)));
fs.copyFileSync(path.join(root, 'shared/rules.js'), path.join(root, 'kiosk/js/rules.js'));
const lines = fs.readFileSync(path.join(root, 'apps-script/dist/Code.gs'), 'utf8').split('\n').length;
console.log('Built apps-script/dist/Code.gs (' + lines + ' lines) and console/js/osc-core.js');

// Kiosk offline file list: every file under kiosk/ (except sw.js and licence texts) is pre-cached.
const kdir = path.join(root, 'kiosk');
const walk = (d) => fs.readdirSync(d, { withFileTypes: true }).flatMap((e) => e.isDirectory() ? walk(path.join(d, e.name)) : [path.relative(kdir, path.join(d, e.name)).split(path.sep).join('/')]);
const kfiles = walk(kdir).filter((f) => f !== 'sw.js' && !/\.(LICENSE|txt)$/.test(f)).sort();
const swPath = path.join(kdir, 'sw.js');
fs.writeFileSync(swPath, fs.readFileSync(swPath, 'utf8').replace(/const FILES = \[[\s\S]*?\];/, 'const FILES = [\n' + kfiles.map((f) => "  '" + f + "'").join(',\n') + '\n];'));
console.log('Kiosk offline cache: ' + kfiles.length + ' files');

// Parallel-run template (Employee ID, Date, Hours), written with the same Excel writer the server uses
const X = require(path.join(root, 'shared/xlsx.js'));
const wb = X.workbook(); wb.title = 'Parallel run register';
const ws = wb.sheet('Register', { widths: { A: 16, B: 14, C: 10, D: 40 }, freeze: 'A2' });
ws.row('A1', ['Employee ID', 'Date', 'Hours', 'Note (optional)'], { b: true, fill: 'E2F2F0', border: true });
[['HK001', '2026-12-01', 12, 'example row: delete before use'], ['HK001', '2026-12-02', 12.5, ''], ['SS003', '2026-12-01', 8, 'left early']].forEach((r, i) => ws.row('A' + (i + 2), r, [{ border: true }, { border: true }, { border: true, fmt: '0.00' }, { border: true }]));
fs.writeFileSync(path.join(root, 'console/templates/parallel_run_template.xlsx'), Buffer.from(wb.build()));
fs.writeFileSync(path.join(root, 'console/templates/parallel_run_template.csv'), 'Employee ID,Date,Hours,Note (optional)\r\nHK001,2026-12-01,12,example row: delete before use\r\nHK001,2026-12-02,12.5,\r\nSS003,2026-12-01,8,left early\r\n');
